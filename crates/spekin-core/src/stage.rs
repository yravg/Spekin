use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// The eight workflow stages, in header order (R-WF-1). The ids match the sample and the URL (/p/:project/:stage).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "lowercase")]
#[ts(export)]
pub enum StageId {
    Planning,
    Spec,
    Design,
    Frontend,
    Backend,
    Integration,
    Testing,
    Deploy,
}

impl StageId {
    /// Every variant, in header order. The single source for the generated TypeScript
    /// `STAGE_IDS` value list; keep it exhaustive together with `as_str` below.
    pub const ALL: [StageId; 8] = [
        StageId::Planning,
        StageId::Spec,
        StageId::Design,
        StageId::Frontend,
        StageId::Backend,
        StageId::Integration,
        StageId::Testing,
        StageId::Deploy,
    ];

    /// The header order is `ALL`; kept as one list so a new variant cannot be added in
    /// one place only.
    pub const ORDER: [StageId; 8] = StageId::ALL;

    /// The lowercase value ts-rs/serde use (`#[serde(rename_all = "lowercase")]`).
    /// Exhaustive on purpose: a new variant fails to compile until this and `ALL` are updated.
    pub const fn as_str(self) -> &'static str {
        match self {
            StageId::Planning => "planning",
            StageId::Spec => "spec",
            StageId::Design => "design",
            StageId::Frontend => "frontend",
            StageId::Backend => "backend",
            StageId::Integration => "integration",
            StageId::Testing => "testing",
            StageId::Deploy => "deploy",
        }
    }
}

/// How a stage reads in the header. The text says it in words; the tone only picks the mark (never colour alone, R-WF-6).
/// ok = ready, half = in progress, ring = not started, warn = needs review, bad = blocked.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "lowercase")]
#[ts(export)]
pub enum StageTone {
    Ok,
    Half,
    Ring,
    Warn,
    Bad,
}

impl StageTone {
    /// Every tone, the single source for the generated TypeScript `STAGE_TONES` value list.
    pub const ALL: [StageTone; 5] = [
        StageTone::Ok,
        StageTone::Half,
        StageTone::Ring,
        StageTone::Warn,
        StageTone::Bad,
    ];

    /// Exhaustive on purpose: a new variant fails to compile until this and `ALL` are updated.
    pub const fn as_str(self) -> &'static str {
        match self {
            StageTone::Ok => "ok",
            StageTone::Half => "half",
            StageTone::Ring => "ring",
            StageTone::Warn => "warn",
            StageTone::Bad => "bad",
        }
    }
}

/// One stage in the header (S35, F101).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Stage {
    pub id: StageId,
    /// Two-digit position label, "01" to "08".
    pub n: String,
    pub name: String,
    pub st: StageTone,
    /// Status in words, for example "In progress · 3 to review".
    pub text: String,
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;
    use std::path::PathBuf;

    /// The directory ts-rs writes its bindings into (`.cargo/config.toml`). The value consts
    /// go in the same directory so `tools/check-contracts.mjs` sees drift on them too.
    fn export_dir() -> PathBuf {
        if let Ok(dir) = std::env::var("TS_RS_EXPORT_DIR") {
            let path = PathBuf::from(&dir);
            if path.is_absolute() {
                return path;
            }
            return PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .join("../..")
                .join(dir);
        }
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/contracts/src/generated")
    }

    /// The generated TypeScript consts, derived from the Rust enums so they cannot drift.
    fn stage_values_ts() -> String {
        let ids = StageId::ALL
            .iter()
            .copied()
            .map(StageId::as_str)
            .map(|s| format!("\"{s}\""))
            .collect::<Vec<_>>()
            .join(", ");
        let tones = StageTone::ALL
            .iter()
            .copied()
            .map(StageTone::as_str)
            .map(|s| format!("\"{s}\""))
            .collect::<Vec<_>>()
            .join(", ");
        [
            "// This file was generated by spekin-core (cargo test). Do not edit by hand."
                .to_string(),
            "// StageId::ALL and StageTone::ALL in crates/spekin-core/src/stage.rs are the source (R-ARC-3)."
                .to_string(),
            String::new(),
            format!("export const STAGE_IDS = [{ids}] as const;"),
            format!("export const STAGE_TONES = [{tones}] as const;"),
        ]
        .join("\n")
            + "\n"
    }

    #[test]
    fn stage_id_all_covers_every_variant() {
        // Exhaustive over the enum: a new StageId variant makes this match fail to compile
        // until it is added here, to StageId::as_str and to StageId::ALL.
        let mut seen = BTreeSet::new();
        for id in StageId::ALL {
            let name = match id {
                StageId::Planning => "planning",
                StageId::Spec => "spec",
                StageId::Design => "design",
                StageId::Frontend => "frontend",
                StageId::Backend => "backend",
                StageId::Integration => "integration",
                StageId::Testing => "testing",
                StageId::Deploy => "deploy",
            };
            assert_eq!(name, id.as_str(), "the TS value must equal the serde value");
            seen.insert(name);
        }
        assert_eq!(StageId::ALL.len(), 8);
        assert_eq!(
            seen.len(),
            StageId::ALL.len(),
            "ALL lists each variant once"
        );
    }

    #[test]
    fn stage_tone_all_covers_every_variant() {
        // Exhaustive over the enum: a new StageTone variant makes this match fail to compile.
        let mut seen = BTreeSet::new();
        for tone in StageTone::ALL {
            let name = match tone {
                StageTone::Ok => "ok",
                StageTone::Half => "half",
                StageTone::Ring => "ring",
                StageTone::Warn => "warn",
                StageTone::Bad => "bad",
            };
            assert_eq!(
                name,
                tone.as_str(),
                "the TS value must equal the serde value"
            );
            seen.insert(name);
        }
        assert_eq!(StageTone::ALL.len(), 5);
        assert_eq!(
            seen.len(),
            StageTone::ALL.len(),
            "ALL lists each variant once"
        );
    }

    #[test]
    fn export_stage_values_bindings() {
        let content = stage_values_ts();
        let dir = export_dir();
        std::fs::create_dir_all(&dir).expect("create the TS export dir");
        std::fs::write(dir.join("StageValues.ts"), &content).expect("write StageValues.ts");
        assert!(content.contains("export const STAGE_IDS"));
        assert!(content.contains("export const STAGE_TONES"));
    }
}
